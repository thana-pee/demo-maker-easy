/** คำนวณงบประมาณจำนวนพยางค์ต่อ 1 ห้องเพลงตาม BPM, Time Signature, ประเภทท่อน และสไตล์นักแต่งเพลง */
export function getSyllableBudgetForBpm(
  bpm = 85,
  timeSignature: TimeSignature = '4/4',
  options?: SyllableBudgetOptions
): SyllableBudget {
  const safeBpm = Number.isFinite(bpm) ? Math.max(40, Math.min(220, Math.round(bpm))) : 85;
  const isWaltz = timeSignature === '3/4';
  const writer = options?.songwriterStyle ?? 'none';
  const thaiGenre = options?.thaiGenre;
  const sectionType = options?.sectionType;
  const isSlowModernPop =
    !isWaltz &&
    safeBpm >= 64 &&
    safeBpm <= 72 &&
    !MELISMATIC_CLASSIC_WRITERS.has(writer) &&
    !(thaiGenre && HERITAGE_GENRES.has(thaiGenre)) &&
    (SLOW_MODERN_POP_WRITERS.has(writer) || Boolean(thaiGenre && SLOW_MODERN_POP_GENRES.has(thaiGenre)));

  let baseMin: number;
  let baseMax: number;
  let tempoFeel: SyllableBudget['tempoFeel'];
  let baseGuidance: string;

  if (safeBpm <= 72 && isSlowModernPop) {
    baseMin = sectionType !== undefined ? 4 : 5;
    baseMax = sectionType !== undefined ? 6 : 8;
    tempoFeel = 'slow';
    baseGuidance =
      sectionType !== undefined
        ? `จังหวะช้าสมัยใหม่ (${safeBpm} BPM, ${timeSignature}) ควรจำกัด 4-6 พยางค์ต่อห้องเพื่อให้ร้องทอดอารมณ์ลงล็อคคอร์ดไม่รัวคำ`
        : `จังหวะช้าสมัยใหม่ (${safeBpm} BPM, ${timeSignature}) ควรใช้ช่วง 5-8 พยางค์ต่อห้องเพื่อให้วลีป๊อป/อาร์แอนด์บีไหลลื่นเป็นธรรมชาติโดยไม่ยัดคำแน่นเกินไป`;
  } else if (safeBpm <= 72) {
    baseMin = 4;
    baseMax = isWaltz ? 7 : 6;
    tempoFeel = 'slow';
    baseGuidance = isWaltz
      ? `จังหวะช้ามาก (${safeBpm} BPM, ${timeSignature}) ควรจำกัด 4-7 พยางค์ต่อห้อง เว้นช่องหายใจให้เอื้อนคำได้`
      : `จังหวะช้ามาก (${safeBpm} BPM, ${timeSignature}) ควรใช้ 4-6 พยางค์ต่อห้อง (สูงสุดไม่เกิน 7 พยางค์) เว้นช่องหายใจและทอดเสียงยาวบนคำเป็น`;
  } else if (safeBpm < 80) {
    baseMin = isWaltz ? 4 : 5;
    baseMax = isWaltz ? 7 : 8;
    tempoFeel = 'slow';
    baseGuidance = isWaltz
      ? `จังหวะช้า (${safeBpm} BPM, ${timeSignature}) ควรจำกัด 4-7 พยางค์ต่อห้อง เว้นช่องหายใจให้เอื้อนคำได้`
      : `จังหวะช้า (${safeBpm} BPM, ${timeSignature}) ควรใช้ 5-8 พยางค์ต่อห้อง ห้ามยัดคำแน่นเกินไปเพื่อให้ร้องซึ้งและลงล็อคคอร์ด`;
  } else if (safeBpm <= 115) {
    baseMin = isWaltz ? 6 : 7;
    baseMax = isWaltz ? 9 : 11;
    tempoFeel = 'medium';
    baseGuidance = `จังหวะกลาง (${safeBpm} BPM, ${timeSignature}) เหมาะกับ 7-11 พยางค์ต่อห้อง จังหวะกระชับ ร้องตามง่าย`;
  } else {
    baseMin = 8;
    baseMax = 12;
    tempoFeel = 'fast';
    baseGuidance = `จังหวะเร็ว (${safeBpm} BPM, ${timeSignature}) ใช้คำกระชับ 8-12 พยางค์ต่อห้อง (สูงสุดไม่เกิน 12 พยางค์) เน้นคำสั้นพยางค์เดียวและสระเปิด`;
  }

  let min = baseMin;
  let max = baseMax;
  const styleNotes: string[] = [];

  if (writer === 'aed-carabao') {
    min = 6;
    max = tempoFeel === 'fast' ? Math.max(12, baseMax) : 11;
    styleNotes.push(
      `สไตล์แอ๊ด คาราบาว (เพื่อชีวิต/สามช่า/คำขวัญติดหู): เปิดงบ ${min}-${max} พยางค์/ห้อง สำหรับคำคล้องจองในวรรคและคำสร้อยปลุกพลัง`
    );
  } else if (writer === 'asanee-chotikul') {
    if (safeBpm >= 104 || sectionType !== undefined) {
      min = 4;
      max = 6;
      styleNotes.push(
        `สไตล์อัสนี โชติกุล (ร็อกคำซ้ำ/จิ๊กโก๋อกหัก): ใช้ช่วง ${min}-${max} พยางค์/ห้อง เพื่อให้ร้องลงบีตร็อกไม่รัวคำ และเว้นช่องให้กีตาร์ลีดรับ`
      );
    } else {
      min = 5;
      max = Math.min(9, Math.max(8, baseMax));
      styleNotes.push(
        `สไตล์อัสนี โชติกุล (ร็อกคำซ้ำ/จิ๊กโก๋อกหัก): ใช้ช่วง ${min}-${max} พยางค์/ห้อง สำหรับซ้ำวลีสั้นใน Bar 1 & Bar 4 และเว้นช่องให้กีตาร์ลีดรับ`
      );
    }
  } else if (writer === 'nga-caravan') {
    min = Math.max(4, baseMin - 1);
    max = tempoFeel === 'fast' ? baseMax : Math.min(10, Math.max(min + 2, baseMax));
    styleNotes.push(
      `สไตล์หงา คาราวาน (เพื่อชีวิต-โฟล์กกวี): ใช้ช่วง ${min}-${max} พยางค์/ห้อง เน้นคำเป็นสระเสียงยาว ภาพธรรมชาติละเมียด และเว้นจังหวะให้กีตาร์โปร่ง/ขลุ่ยหายใจ`
    );
  } else if (DENSE_FLOW_WRITERS.has(writer)) {
    min = baseMin + 1;
    max = Math.min(16, baseMax + 4);
    styleNotes.push(
      writer === 'joey-boy'
        ? `สไตล์โจอี้ บอย: เปิดงบ ${min}-${max} พยางค์/ห้อง สำหรับสัมผัสรัวกระชั้นในวรรค 2-3 จุด และคำตายลงบีตเด้ง`
        : `สไตล์ The TOYS: เปิดงบ ${min}-${max} พยางค์/ห้อง วางกลุ่มคำรัว 16th-note ช่วงต้นห้องสลับสระเปิดเอื้อนท้ายห้อง`
    );
  } else if (PUNCHY_HOOK_WRITERS.has(writer)) {
    min = Math.max(4, baseMin - 1);
    max = baseMax;
    styleNotes.push(
      writer === 'kob-bigass'
        ? `สไตล์กบ บิ๊กแอส (Big Ass / Bodyslam / Labanoon): เปิดหมัดฮุคกระแทกบีต (${min}-${max} พยางค์/ห้อง) วลีคมสู้ชีวิตและรักจริงใจ ตะโกนร้องตามได้ทันทีบนริฟฟ์ร็อก`
        : writer === 'fongbeer-rock'
          ? `สไตล์ฟองเบียร์ ร็อกพูดตรง 2000s (Potato / Zeal / Clash): ใช้ ${min}-${max} พยางค์/ห้อง คำพูดตรงไปตรงมาไม่ประดิษฐ์ ย้ำคำถามหรือความรู้สึกแทงใจลงบีตร็อก`
          : `สไตล์หมัดฮุคกระชับ (${min}-${max} พยางค์/ห้อง): Bar 1 ใช้คำสั้นคม 4-6 พยางค์พุ่งตรงเข้าหู แล้วค่อยขยายภาพในห้องถัดไป`
    );
  } else if (MELISMATIC_CLASSIC_WRITERS.has(writer)) {
    min = Math.max(4, baseMin - 1);
    max = tempoFeel === 'fast' ? baseMax : Math.max(min + 2, baseMax - 1);
    styleNotes.push(
      `สไตล์เอื้อนคำเป็น (${min}-${max} พยางค์/ห้อง): เว้นจังหวะท้ายห้องให้ทอดเสียง/เอื้อนลูกคอสระเสียงยาวอย่างละเมียด`
    );
  } else if (writer === 'fongbeer-pop') {
    styleNotes.push(
      `สไตล์ฟองเบียร์ ป๊อปซึ้งภาษาพูดกินใจ (${min}-${max} พยางค์/ห้อง): ใช้ภาษาพูดเรียบง่ายเล่าเรื่องจริงจากชีวิตประจำวัน เว้นช่องหายใจและย้ำคำจำเพาะหรือตัวเลข/เวลาให้ซึ้งกินใจ`
    );
  } else if (writer !== 'none') {
    styleNotes.push(
      `สไตล์เล่าเรื่องธรรมชาติ (${min}-${max} พยางค์/ห้อง): แบ่งเป็น 2 วลีพูดธรรมชาติ (ต้นห้อง + พักหายใจสั้นๆ + ท้ายห้อง)`
    );
  }

  if (sectionType === 'outro') {
    min = Math.max(3, min - 1);
    max = Math.max(min + 2, max - 2);
    styleNotes.push(
      `ท่อน Outro ลดเหลือ ${min}-${max} พยางค์/ห้อง เพื่อคลายพลังและทิ้งคำเป็นสระเสียงยาวบนโน้ตจบ`
    );
  } else if (sectionType === 'pre-chorus') {
    styleNotes.push(
      `ท่อน Pre-Chorus เร่งน้ำหนักคำช่วงท้ายห้องสุดท้ายเพื่อส่งเข้าคำแรกของท่อนฮุค`
    );
  } else if (sectionType === 'chorus') {
    styleNotes.push(
      `ท่อน Chorus: Bar 1 หมัดฮุคสั้นคม (${Math.max(4, min - 1)}-${Math.max(6, max - 2)} พยางค์) -> Bar 2 ขยายรับสัมผัส (${min}-${max} พยางค์) -> Bar 3 พีคสุด -> Bar 4 ประโยคทองจำแม่น`
    );
  } else if (sectionType === 'verse') {
    styleNotes.push(
      `ท่อน Verse: จัดจังหวะพยางค์เป็นกลุ่มคำพูดธรรมชาติ (2-4 พยางค์ + พักหายใจกลางห้อง + 3-5 พยางค์)`
    );
  }

  const barBudgets: SyllableBudgetBarSlot[] | undefined = sectionType
    ? sectionType === 'chorus'
      ? [
          { barIndex: 0, min: Math.max(4, min - 1), max: Math.max(6, max - 2), role: 'Opening Hook Punchline (หมัดฮุคสั้นคม)' },
          { barIndex: 1, min, max, role: 'Hook Expansion (ขยายภาพ+รับสัมผัสจาก Bar 1)' },
          { barIndex: 2, min, max, role: 'Emotional Climax (จุดพีคอารมณ์และเสียงสูง)' },
          { barIndex: 3, min: Math.max(4, min - 1), max: Math.max(6, max - 1), role: 'Signature Payoff Line (ประโยคทองปิดฮุค)' },
        ]
      : sectionType === 'outro'
        ? [
            { barIndex: 0, min, max, role: 'Closing Reflection (ย้ำภาพจำสุดท้าย)' },
            { barIndex: 1, min: Math.max(3, min - 1), max: Math.max(5, max - 1), role: 'Final Resolution (ปิดจบทอดหางเสียง Root)' },
          ]
        : [
            { barIndex: 0, min, max, role: 'Opening Image (เปิดฉาก/ปูเรื่อง)' },
            { barIndex: 1, min, max, role: 'Development (รับสัมผัส+เคลื่อนไหว)' },
            { barIndex: 2, min, max, role: 'Inner Shift (ความรู้สึกภายใน)' },
            { barIndex: 3, min, max, role: 'Bridge Cue (ทิ้งปมส่งต่อ)' },
          ]
    : undefined;

  return {
    min,
    max,
    tempoFeel,
    guidance: styleNotes.length > 0 ? `${baseGuidance} | ${styleNotes.join(' | ')}` : baseGuidance,
    barStructureGuidance: styleNotes.length > 0 ? styleNotes.join(' | ') : undefined,
    ...(barBudgets ? { barBudgets } : {}),
  };
}

